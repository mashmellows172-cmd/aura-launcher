"""Original quiet UI cues, authored by synthesis. Never plays audio; no sampled brand ringtones."""
from pathlib import Path
import hashlib
import json
import math
import random
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
THEMES = ('nothing','sense','touchwiz','optimus','xperia','razr')
EVENTS = ('launch','menu','select','favorite','index')
DURATIONS = (.105,.135,.085,.175,.045)
RATE = 22050


def synth(theme, event):
    duration = DURATIONS[EVENTS.index(event)]
    shift = (1,.88,1.12,1.25,1.32)[EVENTS.index(event)]
    rng = random.Random(f'aura-v1-{theme}-{event}')
    samples=[]
    for frame in range(round(duration*RATE)):
        t=frame/RATE
        attack=min(1,t/.003)
        release=min(1,(duration-t)/.012)
        decay=math.exp(-t/(duration*.28))
        if theme=='nothing':
            value=(.65*math.sin(math.tau*1300*shift*t)+.35*rng.uniform(-1,1))*math.exp(-t/.014)
        elif theme=='sense':
            value=(math.sin(math.tau*530*shift*t)+.35*math.sin(math.tau*937*shift*t)+.08*rng.uniform(-1,1))*decay
        elif theme=='touchwiz':
            phase=math.tau*shift*(1700*t-3600*t*t)
            value=(math.sin(phase)+.18*math.sin(phase*1.5))*decay
        elif theme=='optimus':
            value=(math.sin(math.tau*740*shift*t)+.28*math.sin(math.tau*1130*shift*t))*decay
        elif theme=='xperia':
            value=(math.sin(math.tau*1640*shift*t)+.4*math.sin(math.tau*2467*shift*t)+.1*math.sin(math.tau*4210*t))*decay
        else:
            value=(math.sin(math.tau*880*shift*t)+.22*math.sin(math.tau*1760*shift*t))*min(1,t/.002)*math.exp(-t/.04)
        if event=='favorite':value *= .7+.3*math.sin(math.pi*t/duration)
        samples.append(value*attack*release)
    peak=max(abs(x) for x in samples) or 1
    return b''.join(struct.pack('<h',round(x/peak*.22*32767)) for x in samples)


def main():
    raw=ROOT/'app/src/main/res/raw';raw.mkdir(parents=True,exist_ok=True)
    records=[]
    for theme in THEMES:
        for event in EVENTS:
            name=f'aura_sound_{theme}_{event}';pcm=synth(theme,event);path=raw/f'{name}.wav'
            with wave.open(str(path),'wb') as stream:
                stream.setnchannels(1);stream.setsampwidth(2);stream.setframerate(RATE);stream.writeframes(pcm)
            records.append(dict(theme=theme,event=event,duration_ms=round(len(pcm)/2/RATE*1000),rate=RATE,channels=1,peak_limit=.22,sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
    folder=ROOT/'artwork/sounds';folder.mkdir(parents=True,exist_ok=True)
    (folder/'manifest.json').write_text(json.dumps(records,indent=2)+'\n',encoding='utf-8',newline='\n')
    rows=['        intArrayOf('+', '.join(f'R.raw.aura_sound_{theme}_{event}' for event in EVENTS)+'),' for theme in THEMES]
    source='''// Generated by tools/generate-theme-sounds.py. No reflection or runtime file search.
package dev.senda.launcher.audio

import dev.senda.launcher.R
import dev.senda.launcher.data.LauncherTheme
import dev.senda.launcher.data.SoundEvent

internal object SoundAssets {
    private val rows = arrayOf(
'''+ '\n'.join(rows)+'''
    )
    fun resource(theme: LauncherTheme, event: SoundEvent): Int = rows[when(theme) {
        LauncherTheme.SENSE -> 1; LauncherTheme.TOUCHWIZ -> 2; LauncherTheme.OPTIMUS -> 3
        LauncherTheme.XPERIA -> 4; LauncherTheme.RAZR -> 5; else -> 0
    }][event.ordinal]
    val allResources: List<Int> = rows.flatMap { it.asList() }
}
'''
    out=ROOT/'app/src/main/java/dev/senda/launcher/audio';out.mkdir(parents=True,exist_ok=True)
    (out/'SoundAssets.kt').write_text(source,encoding='utf-8',newline='\n')
    print(f'Authored {len(records)} original mono PCM cues; no playback performed.')


if __name__=='__main__': main()
