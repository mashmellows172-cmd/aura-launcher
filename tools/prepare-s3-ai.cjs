/** Prepare reviewed imagegen assets. No generation, network or credentials; preserve complete alpha silhouettes. */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
let sharp;
try { sharp = require('sharp'); } catch (_) { sharp = require(process.env.AURA_SHARP_PATH || 'C:/Users/LOQ/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp'); }
const root = path.resolve(__dirname, '..');
const art = path.join(root, 'artwork/touchwiz-s3/ai');
const selected = new Map();
for (const name of fs.readdirSync(art)) {
  const match = /^(.*)-v(\d+)\.png$/.exec(name);
  if (!match) continue;
  const key = match[1], revision = Number(match[2]);
  if (!/^[a-z0-9_]+$/.test(key)) throw new Error('Invalid asset key');
  if (!selected.has(key) || selected.get(key).revision < revision) selected.set(key,{name,revision});
}
(async () => {
  const entries = [];
  for (const [key,item] of selected) {
    const input = path.join(art,item.name);
    const meta = JSON.parse(fs.readFileSync(input.replace(/\.png$/,'.json'),'utf8'));
    if (!/^[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)+$/.test(meta.package)) throw new Error('Invalid package identity');
    const image = await sharp(input).metadata();
    if (!image.hasAlpha) throw new Error('Expected a transparent icon: '+key);
    const resource = 'aura_s3_ai_'+key;
    await sharp(input).resize(192,192,{fit:'contain',background:{r:0,g:0,b:0,alpha:0}})
      .webp({lossless:true}).toFile(path.join(root,'app/src/main/res/drawable-nodpi',resource+'.webp'));
    entries.push({key,package:meta.package,resource,revision:item.revision,source:item.name,
      sha256:crypto.createHash('sha256').update(fs.readFileSync(input)).digest('hex'),review:meta.review});
  }
  if (new Set(entries.map(e=>e.package)).size!==entries.length) throw new Error('Duplicate app identity');
  entries.sort((a,b)=>a.package.localeCompare(b.package));
  const mapping = entries.map(e=>'    '+JSON.stringify(e.package)+' to R.drawable.'+e.resource+',').join('\n');
  const source = '// Generated by tools/prepare-s3-ai.cjs. All entries are AI period interpretations.\npackage dev.senda.launcher.ui.theme.icons\n\nimport dev.senda.launcher.R\n\nprivate val s3Ai = mapOf(\n'+mapping+'\n)\nfun s3AiArtwork(packageName: String): Int? = s3Ai[packageName]\n';
  fs.writeFileSync(path.join(root,'app/src/main/java/dev/senda/launcher/ui/theme/icons/S3AiArtwork.kt'),source);
  fs.writeFileSync(path.join(art,'catalog.json'),JSON.stringify({count:entries.length,entries},null,2)+'\n');
  console.log('Prepared '+entries.length+' AI icons; complete silhouettes fit192px without cropping');
})().catch(error=>{console.error(error.message);process.exitCode=1;});
