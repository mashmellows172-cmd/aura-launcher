"""Build PS4-style identity scenes from the captured Motorola artwork; no runtime tracing.
Requires the private input ZIP and Pillow. Public output contains SVG masters, coverage and lookup.
"""
from pathlib import Path
import argparse, importlib.util, io, json, zipfile
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('installed_generator',ROOT/'tools/generate-installed-app-icons.py')
source=importlib.util.module_from_spec(spec);spec.loader.exec_module(source)
COUNTERPARTS={
 'com.android.settings':'settings','com.google.android.apps.messaging':'messages',
 'com.google.android.contacts':'friends','com.google.android.calendar':'events',
 'com.google.android.apps.nbu.files':'library','com.android.vending':'ps_store_c',
}
def scene(image,mono):
    grid=source.cells(image,side=64,colors=10)
    groups={}
    pixels=[c for row in grid for c in row if c is not None]
    dark_ink=bool(pixels) and sum((c[0]*.2126+c[1]*.7152+c[2]*.0722)<70 for c in pixels)/len(pixels)>.65
    for color,rects in source.paths(grid).items():
        # Keep identity cutouts and contrasting internal details, not just its outer alpha.
        luminance=(color[0]*.2126+color[1]*.7152+color[2]*.0722)/255
        neutral_light=max(color)-min(color)<35 and luminance>.65
        if mono:paint='#FFFFFF'
        elif dark_ink:paint='#FFFFFF' if luminance<.45 else '#83BAF0'
        else:paint='#F4FAFF' if neutral_light else '#83BAF0' if luminance>.20 else '#15365C'
        groups.setdefault(paint,[]).extend(rects)
    s=source.Scene();gradient=s.gradient('plate','#1464B9','#00265E')
    s.rect(3,3,58,58,gradient,2,'#A8D8FF',.6)
    s.path('M4,4 H60 V17 Q31,24 4,17 Z','#FFFFFF',alpha=.07)
    for paint,rects in groups.items():
        d=' '.join(f'M{12+x*.625:.3f},{11+y*.625:.3f}h{w*.625:.3f}v{h*.625:.3f}h{-w*.625:.3f}Z' for x,y,w,h in rects)
        s.path(d,paint)
    s.line(13,55,51,55,'#BCE8FF',.5)
    return s.svg()
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--archive',type=Path,required=True);args=parser.parse_args()
    output=ROOT/'artwork/ps4/app-icons';output.mkdir(parents=True,exist_ok=True)
    inventory=json.loads((ROOT/'artwork/installed-app-icons/manifest.json').read_text(encoding='utf-8'))['entries'];entries=[]
    with zipfile.ZipFile(args.archive) as archive:
        names=set(archive.namelist())
        for app in inventory:
            package=app['package'];kind='captured-app-identity';mono=False
            if package in COUNTERPARTS:
                im=Image.open(ROOT/'app/src/main/res/drawable-nodpi'/('ps4_official_'+COUNTERPARTS[package]+'.png')).convert('RGBA')
                # Sony publication glyphs use black ink and opaque white internal cutouts.
                im.putdata([(255,255,255,max(0,a-r)) for r,g,b,a in im.getdata()]);mono=True;kind='Sony-function-counterpart'
            elif 'monochrome/'+package+'.png' in names:
                im=Image.open(io.BytesIO(archive.read('monochrome/'+package+'.png'))).convert('RGBA');mono=True;kind='app-provided-monochrome'
                box=im.getchannel('A').point(lambda a:255 if a>=64 else 0).getbbox()
                if box:
                    mask=im.getchannel('A').crop(box)
                    filled=sum(a>64 for a in mask.getdata())/(mask.width*mask.height)
                else:filled=1
                if filled>.78:
                    im=source.foreground(archive,package);mono=False;kind='captured-app-identity (solid monochrome rejected)'
            else:im=source.foreground(archive,package)
            bounds=im.getchannel('A').getbbox()
            if bounds:im=im.crop(bounds)
            ratio=64/max(im.size);im=im.resize((max(1,round(im.width*ratio)),max(1,round(im.height*ratio))),Image.Resampling.LANCZOS)
            name='aura_ps4_'+app['key'];output.joinpath(app['key']+'.svg').write_text(scene(im,mono),encoding='utf-8',newline='\n')
            entries.append({'package':package,'label':app['label'],'key':app['key'],'resource':name,'origin':kind})
    output.joinpath('manifest.json').write_text(json.dumps({'count':len(entries),'meaning':'Aura PS4-style interpretations, not official Sony Android app icons.','entries':entries},ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    mapping='\n'.join('    '+json.dumps(e['package'])+' -> R.drawable.'+e['resource'] for e in entries)
    (ROOT/'app/src/main/java/dev/senda/launcher/ui/theme/icons/Ps4AppArtwork.kt').write_text('// Generated by tools/generate-ps4-app-icons.py.\npackage dev.senda.launcher.ui.theme.icons\n\nimport dev.senda.launcher.R\n\nfun ps4AppArtwork(packageName: String): Int? = when(packageName) {\n'+mapping+'\n    else -> null\n}\n',encoding='utf-8',newline='\n')
    print('Authored',len(entries),'PS4 identity scenes')
if __name__=='__main__':main()
